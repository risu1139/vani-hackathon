"""Validate the Persona Design idea against the PS07 dataset.

Writes aggregates only (no names, messages or transcripts) to outputs/.
Signal lexicons are a romanized-Hinglish keyword heuristic: a stand-in for Jev labels.
"""
import glob
import math
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
P = ROOT / "data" / "Persona Files" / "Persona Files"
OUT = ROOT / "outputs" / "2026-10-07-persona-data-validation.md"

SIGNALS = {
    "frustration": r"kitni baar|baar baar|bar bar|pareshan|irritat|mat karo|band karo|call mat|disturb|faltu|bakwas|kyu call|kyon call|bola na|bol diya|bata diya|pagal|dimag",
    "confusion": r"samajh nahi|samjha nahi|samjhi nahi|kya bol|kya matlab|matlab kya|kaun bol|kon bol|kaun hai|phir se|dobara|repeat|sunai nahi|awaaz nahi|aawaz nahi|clear nahi|kya hai ye|kya hai yeh",
    "rush": r"\bbusy\b|jaldi|time nahi|baad me|abhi nahi|driving|gaadi chala|meeting me|\blater\b|call back|baad mein",
    "bot_question": r"\bbot\b|robot|machine|recorded|computer|\bai\b|real person|insaan|ladki ho|aap kaun",
    "interest": r"kitna|price|rate kya|kab aa|kahan milna|kaise kare|kaise hoga|detail|bataiye|batao|interested|chahiye",
    "regional_lang": r"\b(che|chhe|tame|nathi|kem cho|ungal|naan|illa|enna|sollunga|venda|meeru|ledu|cheppandi|enti|aahe|tumhi|mala|ami|apni|korbo|neevu|beku|maadi)\b",
}


def z_test(x1, n1, x2, n2):
    p = (x1 + x2) / (n1 + n2)
    se = math.sqrt(p * (1 - p) * (1 / n1 + 1 / n2))
    z = (x1 / n1 - x2 / n2) / se if se else 0.0
    pval = math.erfc(abs(z) / math.sqrt(2))
    return z, pval


def bucket_matched(treat, ctrl, key="redis_bucket"):
    """Meeting-fixed % of treat and ctrl, both reweighted to treat's lead-type mix (shared buckets only)."""
    w = treat[key].value_counts(normalize=True)
    common = [b for b in w.index if b in set(ctrl[key])]
    w = w[common] / w[common].sum()
    rt, rc = treat.groupby(key).meeting_fixed.mean(), ctrl.groupby(key).meeting_fixed.mean()
    return (w * rt[common]).sum() * 100, (w * rc[common]).sum() * 100


def rate_table(df, col, min_n=300, top=12):
    g = df.groupby(col, dropna=False)["meeting_fixed"].agg(["mean", "size"])
    g = g[g["size"] >= min_n].sort_values("mean", ascending=False).head(top)
    lines = [f"| {col} | calls | meeting-fixed % |", "|---|---|---|"]
    lines += [f"| {k} | {n:,} | {m*100:.1f} |" for k, (m, n) in g.iterrows()]
    spread = (g["mean"].max() - g["mean"].min()) * 100 if len(g) > 1 else 0
    return "\n".join(lines), spread


def main():
    out = ["# Persona Design: data validation (PS07)", "",
           "Generated by `app/validate/profile_persona.py`. Aggregates only. "
           "Signals = romanized keyword heuristic (stand-in for Jev).", ""]

    bc = pd.concat(pd.read_csv(f, low_memory=False) for f in glob.glob(str(P / "*2 of 3" / "ps07_bot_calls_*.csv")))
    bc["meeting_fixed"] = bc["meeting_fixed"].fillna(0).astype(int)
    bc["ts"] = pd.to_datetime(bc["call_start_time"], errors="coerce")
    out += [f"Answered bot calls: {len(bc):,}. Meeting-fixed rate: {bc.meeting_fixed.mean()*100:.1f}%.", ""]

    # 1a. Concurrent trial on 2026-09-30 14:49+: personalis / base_vani (control) / summary_va
    trial = bc[bc.ts >= pd.Timestamp("2026-09-30 14:49")]
    arms = {v: trial[trial.lead_bot_version == v] for v in ["personalis", "base_vani", "summary_va"]}
    base = arms["base_vani"]
    out += ["## 1a. Concurrent script trial, 2026-09-30 from 14:49 (control = base_vani)", "",
            "| arm | calls | meeting-fixed % | bucket-matched: arm vs control | not-interested % | z vs control | p |",
            "|---|---|---|---|---|---|---|"]
    for v, a in arms.items():
        z, pv = z_test(a.meeting_fixed.sum(), len(a), base.meeting_fixed.sum(), len(base))
        mt, mc = bucket_matched(a, base)
        ni = (a.disposition_label == "Not Interested").mean() * 100
        out.append(f"| {v} | {len(a):,} | {a.meeting_fixed.mean()*100:.1f} | {mt:.1f} vs {mc:.1f} | {ni:.1f} | "
                   + ("-" if v == "base_vani" else f"{z:.2f}") + " | " + ("-" if v == "base_vani" else f"{pv:.3f}") + " |")
    out += ["", "Disposition mix (%):", "",
            pd.concat({v: a.disposition_label.value_counts(normalize=True) for v, a in arms.items()}, axis=1)
            .mul(100).round(1).to_markdown(), ""]

    # 1b. last_met_d vs main_vani, same weeks (2026-06-16..07-14), daily paired
    w = bc[bc.ts.between("2026-06-16", "2026-07-14 23:59")].copy()
    L, M = w[w.lead_bot_version == "last_met_d"], w[w.lead_bot_version == "main_vani"]
    mt, mc = bucket_matched(L, M)
    w = w[w.lead_bot_version.isin(["last_met_d", "main_vani"])]
    dd = w.groupby([w.ts.dt.date, "lead_bot_version"]).meeting_fixed.mean().unstack().dropna()
    out += ["## 1b. `last_met_d` vs `main_vani`, same weeks (2026-06-16 to 07-14)", "",
            f"- last_met_d: {len(L):,} calls, {L.meeting_fixed.mean()*100:.1f}% meeting-fixed; "
            f"main_vani: {len(M):,} calls, {M.meeting_fixed.mean()*100:.1f}%.",
            f"- Bucket-matched: {mt:.1f}% vs {mc:.1f}%.",
            f"- Daily paired: last_met_d higher on {int((dd.last_met_d > dd.main_vani).sum())} of {len(dd)} days; "
            f"mean daily gap {(dd.last_met_d - dd.main_vani).mean()*100:+.1f} pts.", ""]

    # 2. Seller traits vs outcome
    sf = pd.concat(pd.read_csv(f, low_memory=False) for f in glob.glob(str(P / "*1 of 3" / "ps07_seller_files_part*.csv")))
    traits = ["annual_turnover", "business_type", "nature_of_business", "top_category_group", "seller_state",
              "showed_frustration", "asked_if_talking_to_bot", "already_in_touch_with_executive"]
    j = bc.merge(sf[["fk_glusr_usr_id"] + traits], on="fk_glusr_usr_id", how="left")
    out += ["## 2. Seller traits vs meeting-fixed rate (call level)", "",
            "`showed_frustration`, `asked_if_talking_to_bot` and `already_in_touch_with_executive` are derived "
            "from the same calls (leakage); read them as descriptive, not predictive.", ""]
    spreads = {}
    for t in traits:
        tbl, spread = rate_table(j, t)
        spreads[t] = spread
        out += [f"### {t} (spread {spread:.1f} pts)", "", tbl, ""]

    # 3. Turn-level signals
    tt = pd.read_csv(P / "Seller-Fit Adaptive Voice Persona - Dataset 1 of 3" / "ps07_call_turns.csv", low_memory=False)
    s = tt[tt.speaker == "seller"].copy()
    s["text_l"] = s.text.fillna("").str.lower()
    s["seller_turn_idx"] = s.groupby("attempt_id").cumcount()
    for k, rx in SIGNALS.items():
        s[k] = s.text_l.str.contains(rx, regex=True)
    calls = s.groupby("attempt_id").agg(n_seller_turns=("seller_turn_idx", "max"),
                                        **{k: (k, "any") for k in SIGNALS})
    first = {k: s[s[k]].groupby("attempt_id").seller_turn_idx.min() for k in SIGNALS}
    calls = calls.join(bc.drop_duplicates("attempt_id").set_index("attempt_id")[["meeting_fixed", "disposition_label"]], how="inner")
    base = calls.meeting_fixed.mean()
    out += ["## 3. Live signals in transcripts", "",
            f"{len(calls):,} calls with turn transcripts; {len(s):,} seller turns; base meeting-fixed {base*100:.1f}%.", "",
            "| signal | % of calls | meeting-fixed % when present | when absent | first seen after seller turn 1 (mid-call) |",
            "|---|---|---|---|---|"]
    for k in SIGNALS:
        has = calls[calls[k]]
        mid = (first[k].reindex(has.index) >= 1).mean() if len(has) else float("nan")
        out.append(f"| {k} | {calls[k].mean()*100:.1f} | {has.meeting_fixed.mean()*100:.1f} | "
                   f"{calls[~calls[k]].meeting_fixed.mean()*100:.1f} | {mid*100:.0f}% |")
    anysig = calls[["frustration", "confusion", "rush", "bot_question", "regional_lang"]].any(axis=1)
    out += ["", f"Calls with at least one negative/adaptation signal: {anysig.mean()*100:.1f}%.", ""]

    # 4. Regional language by state
    s2 = s.merge(sf[["fk_glusr_usr_id", "seller_state"]], on="fk_glusr_usr_id", how="left")
    reg = s2.groupby("attempt_id").agg(state=("seller_state", "first"), regional=("regional_lang", "any"))
    rs = reg.groupby("state").regional.agg(["mean", "size"])
    rs = rs[rs["size"] >= 100].sort_values("mean", ascending=False).head(10)
    out += ["## 4. Non-Hindi regional-language markers by seller state (states with 100+ transcribed calls)", "",
            "| state | calls | % with regional markers |", "|---|---|---|"]
    out += [f"| {k} | {n:,} | {m*100:.1f} |" for k, (m, n) in rs.iterrows()]

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    print("\nTRAIT SPREADS", {k: round(v, 1) for k, v in spreads.items()}, file=sys.stderr)


if __name__ == "__main__":
    main()
